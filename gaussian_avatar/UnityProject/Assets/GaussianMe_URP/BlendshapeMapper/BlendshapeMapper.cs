    int IndexOf(string name)
    {
        for (var i = targetBlendshapeName.Length - 1; i >= 0; --i)
        {
            if (targetBlendshapeName[i] == name)
            {
                return i;
            }
        }
        return -1;
    }

    public SkinnedMeshRenderer smr;

    private Dictionary<int, float[]> runtimeMap = new Dictionary<int, float[]>();
    private float[] mergedBlendShape = new float[targetBlendshapeName.Length];
    private int[] indexMap = new int[targetBlendshapeName.Length];

    void Start()
    {
        if (smr == null || !(smr.sharedMesh is Mesh mesh))
        {
            return;
        }

        runtimeMap.Clear();
        foreach (var (name, value) in mappingData)
        {
            var index = mesh.GetBlendShapeIndex(name);
            runtimeMap[index] = value;
        }

        for (var i = 0; i < mesh.blendShapeCount; ++i)
        {
            var index = IndexOf(mesh.GetBlendShapeName(i));
            if (index != -1)
            {
                indexMap[index] = i;
            }
        }
    }

    void MergeData(float weight, float[] values)
    {
        for (var i = mergedBlendShape.Length - 1; i >= 0; --i)
        {
            mergedBlendShape[i] = Mathf.Clamp(mergedBlendShape[i] + values[i] * weight, 0f, 100f);
        }
    }

    void ProcessBlendshapes()
    {
        foreach (var (index, value) in runtimeMap)
        {
            var weight = smr.GetBlendShapeWeight(index);

            MergeData(weight, value);

            smr.SetBlendShapeWeight(index, 0f);
        }
    }

    void ResetWeights()
    {
        for (var i = mergedBlendShape.Length - 1; i >= 0; --i)
        {
            mergedBlendShape[i] = 0f;
        }
    }

    void UpdateBlendshapes()
    {
        for (var i = indexMap.Length - 1; i >= 0; --i)
        {
            smr.SetBlendShapeWeight(indexMap[i], mergedBlendShape[i]);
        }
    }

    void Update()
    {
        if (runtimeMap.Count == 0 || smr == null)
        {
            return;
        }

        ResetWeights();
        ProcessBlendshapes();
    }

    void LateUpdate()
    {
        if (runtimeMap.Count == 0 || smr == null)
        {
            return;
        }

        UpdateBlendshapes();
    }
